/**
 * Содержимое посадочных страниц «услуга + город».
 *
 * Тексты заданы здесь, а не тянутся из API категорий, по двум причинам.
 * Во-первых, страницы должны собираться статически: зависеть от базы во время
 * сборки — значит ронять весь сайт, когда API недоступен. Во-вторых, текст под
 * поиск пишется руками: автоматически размноженные страницы-пустышки поисковик
 * ранжирует хуже, чем их отсутствие, и человеку они тоже ничего не дают.
 *
 * Города — только те, где есть кого позвать. Страница под город без
 * поставщиков приводит человека в никуда, и это хуже, чем не показаться в
 * выдаче вовсе.
 */

export interface LandingCity {
  slug: string;
  name: string;
  /** Предложный падеж: «в Астане», «в Алматы». */
  inCity: string;
}

