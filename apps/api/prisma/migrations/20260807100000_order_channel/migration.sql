--
-- Это не то же самое, что source: source отвечает «откуда человек пришёл»
-- (google, 2gis, direct), а канал — «где он разговаривал». Смешивать нельзя,
-- иначе заявки из WhatsApp полезли бы в отчёт по рекламным источникам,
-- которыми они не являются.
--
-- Существующим строкам ставится WEB: до появления бота других заявок не было,
-- а те, что пришли из WhatsApp за время тестов, всё равно уже не различить.
ALTER TABLE "Order" ADD COLUMN "channel" TEXT NOT NULL DEFAULT 'WEB';
