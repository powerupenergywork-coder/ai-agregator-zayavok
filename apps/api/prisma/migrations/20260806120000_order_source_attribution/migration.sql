-- Откуда пришёл человек, оформивший заявку.
--
-- Без этого после месяца рекламы нельзя сказать, какой канал принёс заказы, а
-- какой сжёг бюджет. Заполняется один раз, при создании черновика: позже
-- человек ходит по сайту, метки теряются, и «последний клик» приписал бы
-- заказ не тому каналу.
ALTER TABLE "Order"
  ADD COLUMN "source" TEXT,
  ADD COLUMN "sourceParams" JSONB,
  ADD COLUMN "landingPath" TEXT;

-- Под отчёт «откуда приходят» в админке.
CREATE INDEX "Order_source_idx" ON "Order"("source");
