/**
 * Распознаватели по отдельности: срабатывают там, где должны, и молчат там,
 * где не должны.
 *
 * Фразы взяты из настоящих переписок. Отрицательные случаи здесь важнее
 * положительных: ложное срабатывание закрывает живую заявку или добавляет
 * исполнителю категорию, от которой он отказался.
 *
 * Регулярки берутся из собранного кода, а не копируются сюда: копия
 * расходится с оригиналом молча.
 */
import { readCompiled, buildScope } from "./lib/source.mjs";

const router = readCompiled("whatsapp/whatsapp-router.service.js");
const onboarding = readCompiled("whatsapp/whatsapp-onboarding.service.js");
const orders = readCompiled("orders/orders.service.js");

const R = buildScope(router, [
  "PRICE_QUESTION_RE",
  "WANTS_HUMAN_RE",
  "CLIENT_CANCEL_RE",
  "ENOUGH_CALLS_RE",
  "FOUND_EXECUTOR_RE",
  "AD_CLICK_TOKEN_RE",
]);
const O = buildScope(onboarding, ["DENIAL_WORDS", "looksLikeDenial"]);
const S = buildScope(orders, ["looksInformative"]);

const failures = [];
let checked = 0;

/** re — регулярка или предикат; cases — [фраза, ожидание]. */
function suite(label, re, cases, extraArg) {
  const run = typeof re === "function" ? (t) => re(t, extraArg) : (t) => re.test(t);
  for (const [text, want] of cases) {
    checked++;
    if (run(text.trim()) !== want) {
      failures.push(`${label}: «${text}» ${want ? "не распознано" : "сработало ошибочно"}`);
    }
  }
}

