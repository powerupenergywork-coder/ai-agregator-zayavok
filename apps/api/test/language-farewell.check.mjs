/**
 * Просьба о языке и прощание — оба из переписок 1 сентября.
 *
 * +7 778 373 0583, 12:07: «Можна по казахский?» Списки точных фраз ждали
 * дословного «қазақша», просьба прошла мимо, и человек остался на русском.
 *
 * Заявка №155, 16:16: голосовое «Все, спасибо, рахмет вам!» — попрощался. Бот
 * расшифровал, показал текст и спросил «На какую дату нужен вывоз?».
 *
 * Отрицательных случаев здесь больше положительных, и намеренно: ложное
 * переключение языка уводит весь разговор, а ложное прощание закрывает живой
 * черновик.
 */
import { readCompiled, buildScope } from "./lib/source.mjs";

const src = readCompiled("whatsapp/whatsapp-router.service.js");
const { WANTS_KK_RE, WANTS_RU_RE, FAREWELL_RE } = buildScope(src, [
  "WANTS_KK_RE",
  "WANTS_RU_RE",
  "FAREWELL_RE",
]);

const failures = [];
let checked = 0;

function suite(label, re, cases) {
  for (const [text, want] of cases) {
    checked++;
    if (re.test(text.trim().toLowerCase()) !== want) {
      failures.push(`${label}: «${text}» ${want ? "не распознано" : "сработало ошибочно"}`);
    }
  }
}

// ── Просьба перейти на казахский ───────────────────────────────────────────
suite("на казахский", WANTS_KK_RE, [
  ["Можна по казахский?", true],
  ["Можно на казахском", true],
  ["по казахски", true],
  ["давайте по-казахски", true],
  ["қазақша", true],
  ["қазақ тілінде", true],
  ["казакша", true],
  // Не просьба о языке
  ["Нужен вывоз мусора", false],
  ["Астана", false],
  ["Самосвал 25 тонн", false],
  ["Асхат", false],
]);

// ── Просьба перейти на русский ─────────────────────────────────────────────
suite("на русский", WANTS_RU_RE, [
  ["можно по русски", true],
  ["на русском", true],
  ["давайте по-русски", true],
  ["орысша", true],
  ["Нужен манипулятор", false],
  ["Караганда", false],
]);

// ── Прощание ───────────────────────────────────────────────────────────────
suite("прощание", FAREWELL_RE, [
  // Реплика заявки №155, дословно
  ["Все, спасибо, рахмет вам!", true],
  ["Всё, спасибо", true],
  ["всё спасибо", true],
  ["Все, большое спасибо", true],
  ["до свидания", true],
  ["всего доброго", true],
  ["сау болыңыз", true],
  ["спасибо вам", true],
  ["рахмет сізге", true],
  // Голое «спасибо» посреди разговора — вежливость, а не конец.
  // Закрыть на нём черновик значит выбросить живую заявку.
  ["спасибо", false],
  ["Спасибо!", false],
  ["рахмет", false],
  ["ок спасибо", false],
  // Обычные ответы
  ["Астана", false],
  ["Сегодня", false],
  ["Самосвал 25 тонн", false],
  ["адрес Абая 10", false],
  ["не надо", false],
]);

export default { name: "язык и прощание", checked, failures };
