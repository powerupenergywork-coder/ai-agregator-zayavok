/**
 * Вопрос вместо имени — на него отвечают, а не переспрашивают.
 *
 * 30 августа, +7 708 889 1256: «Мне нужна работа, Газель… У меня категории B
 * и C. Вам нужен водитель?» Человек спросил прямо и получил «Кажется, это
 * вопрос, а не имя 🙂» плюс тот же вопрос про имя. На его вопрос не ответили
 * ни разу, и разговор на этом кончился.
 *
 * Проверяем три вещи: пояснение приходит на вопрос, НЕ приходит на повтор
 * команды «поставщик» (там объяснять нечего) и не мешает обычному имени.
 */
import { makeOnboarding } from "./lib/onboarding-harness.mjs";

const failures = [];
let checked = 0;
const check = (ok, what) => {
  checked++;
  if (!ok) failures.push(what);
};

const chatId = "77088891256@c.us";
const phone = "+77088891256";
const text = (t) => ({ text: t });

/** Прогнать одну реплику на шаге имени и вернуть, что ответил бот. */
async function replyTo(message) {
  const { service, sent } = makeOnboarding();
  await service.start(chatId, phone, "ru");
  sent.length = 0;
  await service.handleIncoming(chatId, phone, text(message), "ru");
  return sent.map((m) => m.body ?? "").join("\n---\n");
}

const explains = (out) => /не нанимаем на работу/i.test(out);
const asksName = (out) => /как вас записать/i.test(out);

// ── Реплика того самого человека ───────────────────────────────────────────
{
  const out = await replyTo("Да, меня это заинтересовало. У меня категории B и C. Мне нужна работа. Вам нужен водитель?");
  check(explains(out), "на прямой вопрос «вам нужен водитель?» сервис не объяснён");
  check(asksName(out), "после пояснения имя не переспрошено");
  check(
    /таких заявок у нас нет/i.test(out),
    "не сказано главного: водителю без своей техники заявок не будет",
  );
}

// ── Другие вопросы новичка ─────────────────────────────────────────────────
for (const q of [
  "А что это за сервис?",
  "Как вы работаете?",
  "Сколько стоит?",
  "Вы платите зарплату?",
]) {
  const out = await replyTo(q);
  check(explains(out), `вопрос «${q}» остался без пояснения`);
}

// ── Повтор команды: объяснять нечего ───────────────────────────────────────
{
  const out = await replyTo("поставщик");
  check(!explains(out), "на повтор команды «поставщик» зря отправлено пояснение");
  check(asksName(out), "на повтор команды имя не переспрошено");
}

// ── Обычное имя проходит как раньше ────────────────────────────────────────
for (const name of ["Асхат", "ТОО Стройтех", "Жарбол"]) {
  const out = await replyTo(name);
  check(!explains(out), `на имя «${name}» зря отправлено пояснение`);
  check(!asksName(out), `имя «${name}» не принято — бот переспросил`);
}

export default { name: "пояснение о сервисе", checked, failures };
