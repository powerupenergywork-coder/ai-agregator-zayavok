/**
 * Исполнитель не должен попадать в сценарий заказчика.
 *
 * Два случая подряд. 13 октября, заявка №209: «Не мне нужна заявка Я сам
 * грузчик» — фраза ушла в пояснение, заявка осталась висеть. 14 октября,
 * заявка №213: исполнитель с манипулятором прислал фото, бот молча завёл на
 * него заявку, и дальше всё написанное — «мен өзім манипулятор айдаймын»,
 * «клиенттер өздері звандай ма» — оседало в её пояснении. Человек четыре раза
 * просил стереть написанное, не был понят и ушёл писать владельцу в личку.
 *
 * Причина одна: исполнительская ветка в handleText работает только пока у
 * сессии НЕТ заявки. Один черновик, заведённый без спроса, закрывает человеку
 * все осмысленные ответы разом.
 *
 * Здесь проверяется: фото известного исполнителя не создаёт заявку, фраза
 * «я сам исполнитель» распознаётся в обоих языках и разбирается до orders.chat,
 * а ошибочный черновик закрывается с объяснением, кто кому звонит.
 */
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readCompiled, buildScope, sliceRegion } from "./lib/source.mjs";

const failures = [];
let checked = 0;
const check = (ok, what) => {
  checked++;
  if (!ok) failures.push(what);
};

const routerSrc = readCompiled("whatsapp/whatsapp-router.service.js");

// ── 1. Фраза «я сам исполнитель» ───────────────────────────────────────────
{
  const { I_AM_SUPPLIER_RE } = buildScope(routerSrc, ["I_AM_SUPPLIER_RE"]);

  for (const [text, want] of [
    // Дословно из переписок 13 и 14 октября
    ["Мен өзим манипулятор айдаймын", true],
    ["Не мне нужна заявка Я сам грузчик", true],
    ["мен өзім жүк көлігін жүргіземін", true],
    ["Мен орындаушымын", true],
    ["я сам манипуляторщик", true],
    ["Я сам вожу самосвал", true],
    ["я исполнитель, зачем мне заявка", true],
    ["мне не нужна заявка, я сам электрик", true],
    ["Я сам оказываю услуги", true],
    // Заказчик. «Я сам» без профессии — обычная клиентская речь
    ["я сам не довезу, нужна газель", false],
    ["Сам не могу поднять, нужен манипулятор", false],
    ["нужен грузчик на завтра", false],
    ["я сам буду на объекте, встречу", false],
    ["Нужна заявка на вывоз мусора", false],
    ["", false],
  ]) {
    checked++;
    if (I_AM_SUPPLIER_RE.test(text) !== want) {
      failures.push(`«${text.slice(0, 48)}»: ${want ? "не распознано как реплика исполнителя" : "ошибочно принято за реплику исполнителя"}`);
    }
  }

  // Проверка чувствительности: вырезаем из регулярки ровно казахскую ветку и
  // убеждаемся, что без неё реплика 14 октября перестаёт распознаваться.
  // Иначе тест выше мог бы проходить на совпадении с какой-то другой частью
  // выражения и ничего не стеречь.
  // Веток две: «мен өзім … айдаймын» и короткая «өзім манипулятор». Фраза
  // 14 октября подходит под обе, поэтому вырезать нужно обе — иначе подмена
  // ничего не докажет.
  const KK_BRANCHES = [
    "мен\\s+өз[іи]м[а-яёәғқңөұүіһ\\s]*(айдаймын|жүргіземін|істеймін|беремін|жұмыс)",
    "өз[іи]м\\s+(манипулятор|кран|жүк|такси)",
  ];
  const source = I_AM_SUPPLIER_RE.source;
  check(
    KK_BRANCHES.every((b) => source.includes(b)),
    "казахские ветки в регулярке не найдены — подмене не на что опереться",
  );
  if (KK_BRANCHES.every((b) => source.includes(b))) {
    const weakened = new RegExp(
      KK_BRANCHES.reduce((acc, b) => acc.split("|" + b).join(""), source),
      I_AM_SUPPLIER_RE.flags,
    );
    check(weakened.source !== source, "обрезанная регулярка совпала с исходной — подмена не состоялась");
    check(
      weakened.test("Мен өзим манипулятор айдаймын") === false,
      "казахская часть не проверяется: без неё «Мен өзим манипулятор айдаймын» всё равно распознаётся",
    );
    check(
      weakened.test("Не мне нужна заявка Я сам грузчик") === true,
      "вырезали лишнее: русская часть тоже перестала работать, проверка стала бессмысленной",
    );
  }
}

// ── 2. Фото исполнителя не создаёт заявку ──────────────────────────────────
{
  const region = sliceRegion(routerSrc, "async handlePhoto(", "async handleVoice(");
  check(region.length > 0, "handlePhoto не найден в скомпилированном коде");

  const guard = region.indexOf("findSupplier");
  const ensure = region.indexOf("ensureOrder");
  check(guard !== -1, "в handlePhoto нет проверки, что отправитель — исполнитель");
  check(
    guard !== -1 && ensure !== -1 && guard < ensure,
    "проверка исполнителя стоит ПОСЛЕ ensureOrder — заявка успеет создаться (так и было с №213)",
  );
  check(
    /currentOrderId/.test(region.slice(0, ensure === -1 ? region.length : ensure)),
    "проверка не смотрит на текущую заявку: исполнитель, который уже оформляет заказ, не сможет приложить фото",
  );
}

// ── 3. Выход из чужого сценария разбирается до разбора текста ──────────────
{
  const region = sliceRegion(routerSrc, "REVIEW_CONFIRM_RE", "isRepeating(");
  check(region.length > 0, "не найдена ветка обработки текста по заявке");

  const exit = region.indexOf("I_AM_SUPPLIER_RE");
  const chat = region.indexOf("orders.chat(");
  check(exit !== -1, "фраза «я сам исполнитель» нигде не проверяется в ветке заявки");
  check(
    exit !== -1 && chat !== -1 && exit < chat,
    "проверка стоит после orders.chat — фраза снова осядет в пояснении к заявке",
  );
  check(
    /isDraftOrder/.test(region),
    "нет ограничения черновиком: по разосланной заявке так пишет исполнитель, которому её прислали",
  );
}

// ── 4. Ответ объясняет, кто кому звонит ────────────────────────────────────
{
  const region = sliceRegion(routerSrc, "async explainSupplierFlow(", "async closeOrderAsNotNeeded(");
  check(region.length > 0, "explainSupplierFlow не найден");
  check(
    /комиссию с заказа мы не берём/i.test(region),
    "в объяснении нет главного для исполнителя — что комиссию мы не берём",
  );
  check(
    /вы видите телефон и звоните сами/i.test(region),
    "не сказано, кто кому звонит, — а это и был вопрос «клиенттер оздери звандайма»",
  );
  check(/қоңырау шалмайды/.test(region), "нет казахской версии объяснения, а человек писал по-казахски");

  const discard = sliceRegion(routerSrc, "async discardOrderStartedBySupplier(", "async explainSupplierFlow(");
  check(
    /discardDraftAsInternal/.test(discard),
    "ошибочная заявка не убирается из клиентской воронки — она испортит статистику",
  );
  check(/clearOrder/.test(discard), "сессия остаётся привязанной к удалённой заявке");
  check(/explainSupplierFlow/.test(discard), "после удаления заявки человеку не объясняют, как всё работает");
}

export default { name: "исполнитель не клиент", checked, failures };
