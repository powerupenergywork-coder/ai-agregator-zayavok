import { env } from "../config/env";

/**
 * «Сегодня» — по времени города, а не по Гринвичу.
 *
 * Прогон 2 сентября, 04:16 по Астане: кнопка «Сегодня» предлагала 1 сентября.
 * Дата бралась через `toISOString()`, а это UTC — для Казахстана он отстаёт на
 * пять часов, и с полуночи до пяти утра «сегодня» означало вчера. Заявка
 * уезжала исполнителю с прошедшей датой, причём именно ночью, когда пишут
 * срочные.
 *
 * Часовой пояс тот же, по которому живёт рассылка (DISPATCH_TIMEZONE): дата в
 * заявке и окно дозвона должны считаться по одним часам, иначе «завтра
 * утром» у клиента и у исполнителя окажутся разными днями.
 *
 * Локаль en-CA выбрана из-за формата: она единственная из распространённых
 * даёт ровно YYYY-MM-DD, без перестановки дня и месяца.
 */
export function isoDateInTimezone(date: Date = new Date()): string {
  return date.toLocaleDateString("en-CA", { timeZone: env.dispatchTimezone });
}

/**
 * Дата через N дней от сегодняшней — тоже по местному времени.
 *
 * Считаем сдвиг по календарной дате, а не прибавлением 24 часов к моменту:
 * прибавление часов около полуночи и в дни перевода стрелок промахивается
 * мимо нужных суток.
 */
export function isoDatePlusDays(days: number, from: Date = new Date()): string {
  const [y, m, d] = isoDateInTimezone(from).split("-").map(Number);
  // Полдень UTC — запас в обе стороны, чтобы сдвиг по дням не съехал через
  // границу суток ни при каком часовом поясе.
  const base = new Date(Date.UTC(y, m - 1, d, 12, 0, 0));
  base.setUTCDate(base.getUTCDate() + days);
  return base.toISOString().slice(0, 10);
}
