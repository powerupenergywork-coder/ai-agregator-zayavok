/** Одна строка про порядок цены. Пусто — если вилки для категории нет. */
export function priceHint(categorySlug: string | null | undefined, lang: Language): string {
  if (!categorySlug) return "";
  const hint = PRICE_HINTS[categorySlug];
  return hint ? hint[lang] : "";
}

/**
 * Готовая фраза для ответа на вопрос о цене и для первой реплики.
 *
 * Одним местом, а не двумя строками в разных файлах: формулировка про
 * «обычно» и «точную назовёт исполнитель» должна быть одинаковой везде, иначе
 * в одном месте она смягчится до обещания.
 */
export function priceHintSentence(categorySlug: string | null | undefined, lang: Language): string {
  const hint = priceHint(categorySlug, lang);
  if (!hint) return "";
  // Вилка нередко кончается сокращением — «плюс 6–8 тыс.», — и точка в нём
  // одновременно закрывает предложение. Без этой проверки в живом сообщении
  // выходило «плюс 6–8 тыс.. Точную назовёт исполнитель».
  const head = hint.endsWith(".") ? hint : `${hint}.`;
  return lang === "kk"
    ? `Бағасы туралы: ${head} Нақты бағаны орындаушы өзі айтады — ол көлемге, қашықтыққа және қолжетімділікке байланысты.`
    : `По цене: ${head} Точную назовёт исполнитель — она зависит от объёма, расстояния и подъезда.`;
}
