/**
 * Порядок цены по категории — то, ради чего человек и пишет первым делом.
 *
 * Двое клиентов из пяти спросили цену первым или вторым сообщением: «какая
 * цена?» (№102) и «Сколько стоит по цене?» (№104). Оба ушли. Мы отвечали
 * честно — «цену назовёт исполнитель», — но для человека это звучит как
 * «не скажем, сначала заполни анкету, потом тебе будут звонить незнакомые
 * люди». Он пришёл узнать порядок суммы, а получил отказ.
 *
 * Так это решено везде: Uber и Яндекс показывают стоимость до заказа,
 * Thumbtack — «typical cost» по услуге и городу. Данные исполнителей для
 * этого не нужны, достаточно рыночной вилки.
 *
 * ВАЖНО про честность формулировки. Это не наша цена и не обещание: мы не
 * знаем ни объёма, ни этажа, ни расстояния. Поэтому везде «обычно» и рядом
 * оговорка, что точную назовёт исполнитель. Названная и не сдержанная вилка
 * хуже её отсутствия: человек приедет к разговору с чувством, что его
 * обманули, и это ударит по исполнителю, а не по нам.
 *
 * Пустая строка = для категории вилки нет, и бот про цену ничего не
 * придумывает. Так же ведёт себя незнакомая категория.
 */
