-- Заявка №117: сделка, записанная провалом.
--
-- 22 августа, манипулятор, Астана. Разослана тринадцати исполнителям, все
-- тринадцать прочитали. Через одиннадцать минут клиент написал:
--
--     «Уже нашел исполнителя.»
--     «Спасибо.»
--
-- и нажал «Закрыть заявку» — кнопку, которая в коде означала «услугу не
-- оказали». Заявка легла в отмены с причиной «Клиент закрыл заявку — услугу
-- не оказали», а исполнителям ушло извинение.
--
-- Кнопки с тех пор переименованы, и слова «уже нашёл» теперь закрывают
-- заявку как сделку. Запись осталась прежней.
--
-- Атрибуцию не ставим. Одиннадцать минут после рассылки и тринадцать
-- прочтений говорят сами за себя, но клиент этого не сказал, а домысливать
-- в свою пользу нельзя — ровно из-за таких домыслов статистика и врёт.
-- found_unknown: нашёл, а через нас или нет — неизвестно.
--
-- Ревизия 29 августа прошла все пятнадцать разосланных заявок, закрытых не
-- сделкой. Эта — единственная с прямым доказательством в переписке. По
-- заявкам №108 и №113, которые я подозревал раньше, доказательств нет:
-- клиенты не сказали об исходе ничего.

BEGIN;

INSERT INTO "OrderStatusEvent" (id, "orderId", "fromStatus", "toStatus", actor, note)
SELECT gen_random_uuid(), id, status, 'COMPLETED', 'manual-fix',
       'Ревизия 29.08: клиент написал «Уже нашел исполнителя» и нажал кнопку, означавшую отмену'
FROM "Order" WHERE number = 117 AND status = 'CANCELLED_BY_CLIENT';

UPDATE "Order"
SET status = 'COMPLETED',
    -- Отрицательная оценка досталась от старого кода: закрывая заявку, он
    -- проставлял её сам — то есть жаловался на сервис от имени клиента,
    -- который написал «спасибо». У found_unknown оценки нет вовсе.
    "clientRatingPositive" = NULL,
    "completedAt" = COALESCE("completedAt", "cancelledAt"),
    "cancelledAt" = NULL,
    "cancelReason" = NULL
WHERE number = 117 AND status = 'CANCELLED_BY_CLIENT';

SELECT number, status, "clientRatingPositive" AS via_us, "completedAt", "cancelledAt"
FROM "Order" WHERE number = 117;

COMMIT;
