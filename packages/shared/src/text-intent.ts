/**
 * Задал ли человек вопрос вместо того, чтобы ответить.
 *
 * Нужно в двух местах, и в обоих цена ошибки несимметрична. В заявке
 * вопрос, принятый за ответ, оседает в поле навсегда: «Так что хотели» в
 * графе «адрес объекта» уезжает поставщику, и поймать это может только
 * человек, читающий заявку глазами. Ложное срабатывание всего лишь заставит
 * переспросить. Поэтому порог намеренно смещён в сторону «переспросить».
 *
 * Вопросительное слово ищем целым словом в любом месте, но только в коротких
 * сообщениях: «вы кто люди» — вопрос, хотя начинается не с «кто», а в
 * длинном рассказе про технику «что» почти всегда часть повествования.
 */
const QUESTION_WORD_RE =
  /(?:^|\s)(что|чего|кто|кого|кому|как|какой|какая|какие|каком|какую|где|куда|когда|почему|зачем|сколько|можно ли|есть ли|кім|қалай|қайда|қашан|неге|қанша|қандай)(?:$|[\s,.!])/i;

const SHORT_MESSAGE_WORDS = 7;

export function looksLikeQuestion(text: string): boolean {
  if (text.includes("?")) return true;
  const words = text.trim().split(/\s+/).length;
  return words <= SHORT_MESSAGE_WORDS && QUESTION_WORD_RE.test(text);
}

/**
 * Строже, чем looksLikeQuestion(): годится ли строка на роль значения поля.
 *
 * Отдельная функция, потому что в заявке нельзя выбрасывать «Нужен кран,
 * можно ли завтра?» — там есть и вопрос, и содержание, и потерять содержание
 * хуже, чем оставить лишний хвост.
 *
 * Признаком содержания считаем цифру («25 тонн, можно?» — это ответ) и
 * запятую: встречный вопрос в разговоре — это одна короткая реплика, а как
 * только человек написал два куска через запятую, он что-то сообщил, и
 * выбрасывать всё целиком уже дороже, чем оставить лишний хвост.
 */
export function isQuestionNotAnswer(text: string): boolean {
  const t = text.trim();
  if (!t || /\d/.test(t) || t.includes(",")) return false;
  return t.split(/\s+/).length <= 5 && looksLikeQuestion(t);
}
